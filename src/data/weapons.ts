const CLASS_BY_CATEGORY: Record<WeaponCategory, ClassId | null> = {
  ar: 'assalto',
  lmg: 'suporte',
  carabina: 'engenheiro',
  sniper: 'reconhecimento',
  dmr: 'reconhecimento',
  smg: null,
  escopeta: null,
  pistola: null,
  'corpo-a-corpo': null,
};

function slotsForCategory(category: WeaponCategory): SlotId[] {
  if (category === 'corpo-a-corpo') return [];
  if (category === 'pistola') return PISTOL_SLOTS;
  if (category === 'escopeta') return SHOTGUN_SLOTS;
  return FULL_SLOTS;
}

type WeaponEntry = Omit<
  Weapon,
  'signatureClass' | 'slots' | 'pellets' | 'drag' | 'season' | 'damage'
> & {
  damage: [number, number][];
  pellets?: number;
  drag?: number;
  season?: number;
  slots?: SlotId[];
};

function buildWeapon(entry: WeaponEntry): Weapon {
  const damage: DamageStep[] = entry.damage.map(([d, distance]) => ({ damage: d, distance }));
  return {
    ...entry,
    damage,
    pellets: entry.pellets ?? 1,
    drag: entry.drag ?? 1,
    season: entry.season ?? 0,
    signatureClass: CLASS_BY_CATEGORY[entry.category],
    slots: entry.slots ?? slotsForCategory(entry.category),
  };
}

