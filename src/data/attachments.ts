export const ATTACHMENTS_BY_ID = new Map<string, Attachment>(ATTACHMENTS.map((a) => [a.id, a]));

/** Decide se um acessório pode ser montado em determinada arma. */
export function isCompatible(attachment: Attachment, weapon: Weapon): boolean {
  if (!weapon.slots.includes(attachment.slot)) return false;

  const { armas, exceto, categories, arquetipos } = attachment.compat;
  if (exceto?.includes(weapon.id)) return false;
  if (armas) return armas.includes(weapon.id);

  const byCategory = categories ? categories.includes(weapon.category) : false;
  const porArquetipo = arquetipos ? arquetipos.includes(weapon.archetype) : false;
  if (!categories && !arquetipos) return true;
  return byCategory || porArquetipo;
}

/** Acessórios compatíveis com uma arma, agrupados pelo slot. */
export function attachmentsForWeapon(weapon: Weapon): Map<string, Attachment[]> {
  const map = new Map<string, Attachment[]>();
  for (const slot of weapon.slots) {
    const list = ATTACHMENTS.filter((a) => a.slot === slot && isCompatible(a, weapon));
    if (list.length > 0) map.set(slot, list);
  }
  return map;
}
