import type { Arma, ArquetipoArma, CategoriaArma, DegrauDano, IdClasse, IdSlot } from './tipos';

/* -------------------------------------------------------------------------- *
 * Procedência dos números
 *
 * Cadência, velocidade de projétil, capacidade, recarga e tempo de mira vêm de
 * levantamentos da comunidade sobre o jogo. As escadas de dano seguem o padrão
 * do Battlefield 6, em que cada degrau é 100 dividido por um número inteiro de
 * tiros — o que permite reconstruir o perfil a partir do "tiros para matar" por
 * distância. Onde não havia medição publicada, o degrau foi derivado de uma arma
 * de mesmo calibre e cadência, e a arma fica marcada como `curado`.
 * -------------------------------------------------------------------------- */

