const CLASSE_DA_CATEGORIA: Record<CategoriaArma, IdClasse | null> = {
  ar: 'assalto',
  lmg: 'suporte',
  carabina: 'engenheiro',
  sniper: 'reconhecimento',
  dmr: 'reconhecimento',
  smg: null,
  escopeta: null,
  pistola: null,
  'corpo-a-corpo': null,
};

function slotsDaCategoria(categoria: CategoriaArma): IdSlot[] {
  if (categoria === 'corpo-a-corpo') return [];
  if (categoria === 'pistola') return SLOTS_PISTOLA;
  if (categoria === 'escopeta') return SLOTS_ESCOPETA;
  return SLOTS_COMPLETOS;
}

type EntradaArma = Omit<
  Arma,
  'classeAssinatura' | 'slots' | 'projeteis' | 'arrasto' | 'temporada' | 'dano'
> & {
  dano: [number, number][];
  projeteis?: number;
  arrasto?: number;
  temporada?: number;
  slots?: IdSlot[];
};

function montar(entrada: EntradaArma): Arma {
  const dano: DegrauDano[] = entrada.dano.map(([d, distancia]) => ({ dano: d, distancia }));
  return {
    ...entrada,
    dano,
    projeteis: entrada.projeteis ?? 1,
    arrasto: entrada.arrasto ?? 1,
    temporada: entrada.temporada ?? 0,
    classeAssinatura: CLASSE_DA_CATEGORIA[entrada.categoria],
    slots: entrada.slots ?? slotsDaCategoria(entrada.categoria),
  };
}

